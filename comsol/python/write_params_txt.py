"""Generate comsol/params.txt (COMSOL Parameters-node import file) and
comsol/java/variants_flat.txt (variant list for the Java driver) from the
YAML single source of truth.

    python comsol/python/write_params_txt.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from common.params import expand_variants, load_base, param_exprs  # noqa: E402

PARAMS_TXT = ROOT / "comsol" / "params.txt"
VARIANTS_FLAT = ROOT / "comsol" / "java" / "variants_flat.txt"
MODEL_CONFIG = ROOT / "comsol" / "java" / "model_config.txt"


def params_txt_text() -> str:
    lines = []
    for name, (expr, desc) in param_exprs().items():
        lines.append(f'{name} {expr} "{desc}"')
    return "\n".join(lines) + "\n"


def variants_flat_text() -> str:
    """One run per line, tab separated:
    set  id  stats  bgn  mobility  fletcher  qsrc  configs  name=expr;name=expr...
    """
    out = ["# GENERATED by comsol/python/write_params_txt.py -- do not edit by hand",
           "# set\tid\tstats\tbgn\tmobility\tfletcher\tqsrc\tconfigs\tparams"]
    core = {r["id"] for r in expand_variants("core")}
    for r in expand_variants("full"):
        s = "core" if r["id"] in core else "full"
        params = ";".join(f"{k}={v}" for k, v in r["params"].items())
        out.append("\t".join([s, r["id"], r["stats"], str(r["bgn"]), r["mobility"],
                              str(bool(r["fletcher"])).lower(), r["qsrc"],
                              ",".join(r["configs"]), params]))
    return "\n".join(out) + "\n"


def caughey_thomas_expr(carrier: str, base: dict | None = None) -> str:
    """Spec §4.3 option M2: mu = mu_min + (mu_max-mu_min)/(1+(N_tot/N_ref)^alpha)."""
    import api_names as api
    c = (base or load_base())["mobility_M2"][carrier]
    ntot = f"({api.name('ND_TOT')}+{api.name('NA_TOT')})"
    return f"{c['mu_min']}+({c['mu_max']}-{c['mu_min']})/(1+({ntot}/{c['N_ref']})^{c['alpha']})"


def model_config_text() -> str:
    """Flat key<TAB>value[<TAB>description] file with the non-parameter parts of
    params_base.yaml, for the Java driver (no YAML parser needed there)."""
    b = load_base()
    out = ["# GENERATED by comsol/python/write_params_txt.py from config/params_base.yaml -- do not edit"]
    r = b["functions"]["rect1"]
    out += [f"rect1.lower\t{r['lower']}", f"rect1.upper\t{r['upper']}", f"rect1.smooth\t{r['smooth']}"]
    for k, (e, d) in b["variables"].items():
        out.append(f"var.{k}\t{e}\t{d}")
    out.append(f"var.mun_CT\t{caughey_thomas_expr('electrons', b)}\tCaughey-Thomas mobility (electrons), option M2")
    out.append(f"var.mup_CT\t{caughey_thomas_expr('holes', b)}\tCaughey-Thomas mobility (holes), option M2")
    for k, v in b["material_fallback"].items():
        out.append(f"mat.{k}\t{v}")
    for k, v in b["mesh"].items():
        out.append(f"mesh.{k}\t{v}")
    for k, v in b["sweeps"].items():
        out.append(f"sweep.{k}\t{','.join(str(x) for x in v) if isinstance(v, list) else v}")
    return "\n".join(out) + "\n"


def main() -> None:
    PARAMS_TXT.write_text(params_txt_text(), encoding="utf-8")
    VARIANTS_FLAT.write_text(variants_flat_text(), encoding="utf-8")
    MODEL_CONFIG.write_text(model_config_text(), encoding="utf-8")
    for p in (PARAMS_TXT, VARIANTS_FLAT, MODEL_CONFIG):
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
