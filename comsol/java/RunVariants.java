  static double[][] globalTable(Model m, String ds) {
    double Ac = pval(m, "Ac"), Pi = pval(m, "Pi_nc+Pi_pc");
    String hs = HS_EXPR, tf = var("TFLUX_X");
    double[] VF = evalGlobal(m, "VF", "V", ds, 0);
    int n = VF.length;
    double[] I = evalGlobal(m, "abs(" + var("I_TERMINAL") + ")", "A", ds, 0);
    double[] Qt = evalGlobal(m, "intop_all(" + hs + ")", "W/m^2", ds, 0);
    double[] Qn = evalGlobal(m, "intop_all((" + hs + ")*(x<Wn+5[um]))", "W/m^2", ds, 0);
    double[] Qp = evalGlobal(m, "intop_all((" + hs + ")*(x>Ltot-Wp-5[um]))", "W/m^2", ds, 0);
    double[] q0 = evalGlobal(m, "pt_n(" + tf + ")", "W/m^2", ds, 0);
    double[] qL = evalGlobal(m, "pt_p(" + tf + ")", "W/m^2", ds, 0);
    double[] Vi = evalGlobal(m, "intop_i(" + var("E_X") + ")", "V", ds, 0);
    double[][] out = new double[GLOBAL_COLS.length][n];
    for (int i = 0; i < n; i++) {
      double J = I[i] / Ac, P = I[i] * VF[i];
      out[0][i] = VF[i]; out[1][i] = I[i]; out[2][i] = J; out[3][i] = P;
      out[4][i] = Ac * Qt[i]; out[5][i] = Ac * Qn[i]; out[6][i] = Ac * Qp[i];
      out[7][i] = -J * Ac * Pi;
      out[8][i] = q0[i]; out[9][i] = qL[i];
      out[10][i] = Double.NaN; out[11][i] = Double.NaN; out[12][i] = Double.NaN;
      out[13][i] = Ac * (q0[i] - qL[i] + J * Pi);
      out[14][i] = P > 0 ? (out[4][i] + out[7][i]) / P : Double.NaN;
      out[15][i] = -Vi[i];
    }
    return out;
  }

  static double[][] pointTemps(Model m, String ds) {
    return new double[][]{evalGlobal(m, "VF", "V", ds, 0), evalGlobal(m, "pt_n(T)", "K", ds, 0),
        evalGlobal(m, "pt_p(T)", "K", ds, 0), evalGlobal(m, "pt_c(T)", "K", ds, 0)};
  }

  static void profiles(Model m, String dsSemi, String dsT, String out, String[] hdr) throws IOException {
    String jx = var("J_X"), ex = var("E_X"), hs = HS_EXPR;
    String[] ex1 = {"x", var("EC"), var("EV"), var("EFN"), var("EFP"), var("N_E"), var("P_H"), var("NDOP"),
        jx + "*" + ex, hs, "(" + hs + ")-" + jx + "*" + ex};
    String[] un1 = {"m", "eV", "eV", "eV", "eV", "1/m^3", "1/m^3", "1/m^3", "W/m^3", "W/m^3", "W/m^3"};
    double[][][] a = evalField(m, ex1, un1, dsSemi);
    double[][][] t = evalField(m, new String[]{"x", "T", var("TFLUX_X")}, new String[]{"m", "K", "W/m^2"}, dsT);
    double[] VFa = evalGlobal(m, "VF", "V", dsSemi, 0), VFt = evalGlobal(m, "VF", "V", dsT, 0);
    String[] cols = {"x", "Ec", "Ev", "Efn", "Efp", "n", "p", "Ndop", "JdotE", "Q_tot", "Q_rec", "T", "tfluxX"};
    for (String vs : CFG.get("sweep.profile_VF").split(",")) {
      double v = Double.parseDouble(vs);
      int i = nearest(VFa, v), k = nearest(VFt, v);
      if (Math.abs(VFa[i] - v) > 1e-9 || Math.abs(VFt[k] - v) > 1e-9) continue;
      int np = a[0][i].length;
      Integer[] order = new Integer[np];
      for (int q = 0; q < np; q++) order[q] = q;
      final double[] xs = a[0][i];
      Arrays.sort(order, Comparator.comparingDouble(q -> xs[q]));
      double[][] data = new double[cols.length][np];
      for (int q = 0; q < np; q++) {
        int o = order[q];
        for (int c = 0; c < 11; c++) data[c][q] = a[c][i][o];
        data[11][q] = t[1][k][o];
        data[12][q] = t[2][k][o];
      }
      String name = vs.endsWith(".0") ? vs.substring(0, vs.length() - 2) : vs;
      String[] h = Arrays.copyOf(hdr, hdr.length + 1);
      h[hdr.length] = "VF: " + v;
      writeCsv(out + "/profiles_VF" + name + ".csv", h, cols, data);
    }
  }

  static int nearest(double[] a, double v) {
    int b = 0;
    for (int i = 1; i < a.length; i++) if (Math.abs(a[i] - v) < Math.abs(a[b] - v)) b = i;
    return b;
  }

  static double[] parseRange(String s) {
    Matcher mm = Pattern.compile("\\s*range\\(([^,]+),([^,]+),([^,]+)\\)\\s*").matcher(s);
    if (!mm.matches()) throw new IllegalArgumentException(s);
    double a = Double.parseDouble(mm.group(1)), d = Double.parseDouble(mm.group(2)), b = Double.parseDouble(mm.group(3));
    int n = (int) Math.round((b - a) / d) + 1;
    double[] r = new double[n];
    for (int i = 0; i < n; i++) r[i] = Math.round((a + d * i) * 1e12) / 1e12;
    return r;
  }

  static double[][] roomSweep(Model m) {
    double[] dTs = parseRange(CFG.get("sweep.dT_sink"));
    String tf = var("TFLUX_X");
    String expr = "Ac*(pt_n(" + tf + ")-pt_p(" + tf + "))+abs(" + var("I_TERMINAL") + ")*(Pi_nc+Pi_pc)";
    List<double[]> rows = new ArrayList<>();
    try {
      String ds = datasetOf(m, STD_ROOM, true);
      for (int k = 0; k < dTs.length; k++) {
        double[] VF = evalGlobal(m, "VF", "V", ds, k + 1), Q = evalGlobal(m, expr, "W", ds, k + 1);
        for (int i = 0; i < VF.length; i++) rows.add(new double[]{VF[i], dTs[k], Q[i]});
      }
    } catch (Exception e) {
      log("parametric dataset export failed (" + firstLine(e) + ") -> driver loop over dT_sink");
      rows.clear();
      m.study(STD_ROOM).feature("param").active(false);
      try {
        for (double d : dTs) {
          m.param().set("dT_sink", String.format(Locale.ROOT, "%.6g[K]", d));
          solve(m, STD_ROOM);
          String ds = datasetOf(m, STD_ROOM, false);
          double[] VF = evalGlobal(m, "VF", "V", ds, 0), Q = evalGlobal(m, expr, "W", ds, 0);
          for (int i = 0; i < VF.length; i++) rows.add(new double[]{VF[i], d, Q[i]});
        }
      } finally {
        m.study(STD_ROOM).feature("param").active(true);
        m.param().set("dT_sink", "0[K]");
      }
    }
    double[][] out = new double[3][rows.size()];
    for (int i = 0; i < rows.size(); i++) for (int c = 0; c < 3; c++) out[c][i] = rows.get(i)[c];
    return out;
  }

  static void exportVariant(Model m, Map<String, String> r) throws IOException {
    String out = ROOT + "/results/" + r.get("id");
    String[] hdr = header(r);
    List<String> cfgs = Arrays.asList(r.get("configs").split(","));
    solve(m, STD_EQ_IV);
    String d1 = datasetOf(m, STD_EQ_IV, false);
    double[][] g = globalTable(m, d1);
    String dT = d1;
    if (cfgs.contains("B")) {
      solve(m, STD_FLOAT);
      String d3 = datasetOf(m, STD_FLOAT, false);
      double[][] fl = pointTemps(m, d3);
      writeCsv(out + "/float_vs_VF.csv", hdr, new String[]{"VF", "T_P1", "T_P5", "T_P3"}, fl);
      for (int i = 0; i < g[0].length; i++) {
        g[10][i] = interp(g[0][i], fl[0], fl[1]);
        g[11][i] = interp(g[0][i], fl[0], fl[2]);
        g[12][i] = interp(g[0][i], fl[0], fl[3]);
      }
      dT = d3;
    }
    if (cfgs.contains("C")) {
      solve(m, STD_LAT);
      String d4 = datasetOf(m, STD_LAT, false);
      writeCsv(out + "/lat_vs_VF.csv", hdr, new String[]{"VF", "T_P1", "T_P5", "T_P3"}, pointTemps(m, d4));
      if (!cfgs.contains("B")) dT = d4;
    }
    writeCsv(out + "/global_vs_VF.csv", hdr, GLOBAL_COLS, g);
    profiles(m, d1, dT, out, hdr);
    if (cfgs.contains("A")) {
      solve(m, STD_ROOM);
      writeCsv(out + "/room_sweep.csv", hdr, new String[]{"VF", "dT_sink", "Q_room"}, roomSweep(m));
    }
    if (r.get("id").equals("V0") || r.get("id").equals("V1")) {
      StudyFeature st = m.study(STD_EQ_IV).feature("stat");
      String fwd = st.getStringArray("plistarr")[0];
      st.set("plistarr", new String[]{REVERSE_VF});
      try {
        solve(m, STD_EQ_IV);
        String dr = datasetOf(m, STD_EQ_IV, false);
        writeCsv(out + "/reverse_bias_global.csv", hdr, GLOBAL_COLS, globalTable(m, dr));
        double[][][] f = evalField(m, new String[]{"x", HS_EXPR}, new String[]{"m", "W/m^3"}, dr);
        int last = f[0].length - 1;
        writeCsv(out + "/reverse_bias_profile.csv", hdr, new String[]{"x", "Q_tot"}, new double[][]{f[0][last], f[1][last]});
      } finally {
        st.set("plistarr", new String[]{fwd});
      }
    }
    log("variant " + r.get("id") + " exported to " + out);
  }

  public static Model run() {
    Model last = null;
    try {
      init();
      readBuildInfo();
      try { VERSION = ModelUtil.getComsolVersion(); } catch (Exception ignored) { /* keep default */ }
      List<String> failed = new ArrayList<>();
      for (Map<String, String> r : readRuns()) {
        String needsLib = (r.get("bgn").equals("slotboom") || Boolean.parseBoolean(r.get("fletcher"))) ? "yes" : "no";
        if (needsLib.equals("yes") && !MATERIAL_USED.equals("library")) {
          log(r.get("id") + " needs the library material (BGN/Fletcher); skipped");
          failed.add(r.get("id"));
          continue;
        }
        if (r.get("mobility").equals("M1") && !MATERIAL_USED.equals("library")) r.put("mobility", "M2");
        Model m = ModelUtil.load("Model", ROOT + "/comsol/models/pin_peltier_base.mph");
        try {
          applyVariant(m, r);
          exportVariant(m, r);
        } catch (ApiNameError e) {
          log("ERROR " + e.getMessage());
          throw e;
        } catch (Exception e) {
          log("variant " + r.get("id") + " failed: " + firstLine(e));
          failed.add(r.get("id"));
        } finally {
          last = m;
          ModelUtil.remove("Model");
        }
      }
      if (!failed.isEmpty()) log("failed/skipped runs: " + failed);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
    return last;
  }

  public static void main(String[] args) {
    run();
  }
