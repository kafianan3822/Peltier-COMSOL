  /** Linear interpolation; NaN outside the table. */
  static double interp(double x, double[] xs, double[] ys) {
    for (int i = 0; i + 1 < xs.length; i++)
      if (xs[i] <= x && x <= xs[i + 1]) return ys[i] + (ys[i + 1] - ys[i]) * (x - xs[i]) / (xs[i + 1] - xs[i]);
    return Double.NaN;
  }

