  static void init() throws IOException {
    String r = System.getenv("PIN_PELTIER_ROOT");
    if (r == null) r = System.getProperty("pin.root", "../..");
    ROOT = new File(r).getCanonicalPath();
    new File(ROOT + "/comsol/models").mkdirs();
    for (String line : Files.readAllLines(Paths.get(ROOT, "comsol", "java", "model_config.txt"), StandardCharsets.UTF_8)) {
      if (line.startsWith("#") || line.trim().isEmpty()) continue;
      String[] f = line.split("\t", -1);
      CFG.put(f[0], f.length > 1 ? f[1] : "");
      if (f.length > 2) CFG.put(f[0] + ".desc", f[2]);
    }
  }

  /** Parameters node import file: name  expr  "desc". */
  static List<String[]> readParams() throws IOException {
    List<String[]> out = new ArrayList<>();
    Pattern p = Pattern.compile("^(\\S+)\\s+(\\S+)\\s+\"(.*)\"\\s*$");
    for (String line : Files.readAllLines(Paths.get(ROOT, "comsol", "params.txt"), StandardCharsets.UTF_8)) {
      Matcher m = p.matcher(line);
      if (m.matches()) out.add(new String[]{m.group(1), m.group(2), m.group(3)});
    }
    return out;
  }

