  // ------------------------------------------------------------------ mesh (§4.5)
  static void buildMesh(Model m, double factor) {
    int nd = (int) Math.round(Double.parseDouble(CFG.get("mesh.n_doped")) * factor);
    int ni = (int) Math.round(Double.parseDouble(CFG.get("mesh.n_ihalf")) * factor);
    int ratio = (int) Math.round(Double.parseDouble(CFG.get("mesh.elemratio_ihalf")));
    if (Arrays.asList(m.component(COMP).mesh().tags()).contains(MESH)) m.component(COMP).mesh().remove(MESH);
    MeshSequence mesh = m.component(COMP).mesh().create(MESH);
    verify("MESH_EDGE", MESH_EDGE, () -> mesh.create("edg1", MESH_EDGE));
    mesh.feature("edg1").selection().all();
    Object[][] specs = {{"dis_n", 1, false, false}, {"dis_p", 4, false, false},
                        {"dis_iL", 2, true, false}, {"dis_iR", 3, true, true}};
    for (Object[] s : specs) {
      String tag = (String) s[0];
      int dom = (Integer) s[1];
      boolean graded = (Boolean) s[2];
      boolean rev = REVERSE.getOrDefault(tag, (Boolean) s[3]);
      verify("MESH_DIST", MESH_DIST, () -> mesh.feature("edg1").create(tag, MESH_DIST));
      MeshFeature d = mesh.feature("edg1").feature(tag);
      d.selection().set(new int[]{dom});
      if (!graded) {
        verify("DIST_NUMELEM", DIST_NUMELEM, () -> d.set(DIST_NUMELEM, nd));
      } else {
        verify("DIST_TYPE", DIST_TYPE, () -> d.set(DIST_TYPE, "predefined"));
        verify("DIST_ELEMCOUNT", DIST_ELEMCOUNT, () -> d.set(DIST_ELEMCOUNT, ni));
        verify("DIST_ELEMRATIO", DIST_ELEMRATIO, () -> d.set(DIST_ELEMRATIO, ratio));
        verify("DIST_GROWTH", DIST_GROWTH, () -> d.set(DIST_GROWTH, "geometric"));
        verify("DIST_REVERSE", DIST_REVERSE, () -> d.set(DIST_REVERSE, rev));
      }
    }
    mesh.run();
    assertMeshGrading(m, true);
    log("mesh: " + nd + "+" + ni + "+" + ni + "+" + nd + " elements (mesh_factor=" + factor + ")");
  }

  /** Smallest element of each i-half must sit at its junction end (spec §4.5). */
  static void assertMeshGrading(Model m, boolean retry) {
    double[][] v = m.component(COMP).mesh(MESH).getVertex();
    double[] x = v[0].clone();
    Arrays.sort(x);
    double Wn = pval(m, "Wn"), Xc = pval(m, "Xc"), Wi = pval(m, "Wi");
    boolean ok = true;
    Object[][] halves = {{"dis_iL", Wn, Xc, true}, {"dis_iR", Xc, Wn + Wi, false}};
    for (Object[] h : halves) {
      double lo = (Double) h[1], hi = (Double) h[2];
      boolean fineAtLo = (Boolean) h[3];
      double hLo = Double.NaN, hHi = Double.NaN;
      for (int i = 0; i + 1 < x.length; i++) {
        double xm = 0.5 * (x[i] + x[i + 1]);
        if (xm > lo && xm < hi) {
          if (Double.isNaN(hLo)) hLo = x[i + 1] - x[i];
          hHi = x[i + 1] - x[i];
        }
      }
      boolean good = fineAtLo ? hLo < hHi : hHi < hLo;
      log("mesh " + h[0] + ": h(junction)=" + (fineAtLo ? hLo : hHi) + " h(centre)=" + (fineAtLo ? hHi : hLo));
      if (!good) {
        ok = false;
        String tag = (String) h[0];
        MeshFeature d = m.component(COMP).mesh(MESH).feature("edg1").feature(tag);
        boolean cur = d.getBoolean(DIST_REVERSE);
        REVERSE.put(tag, !cur);
        d.set(DIST_REVERSE, !cur);
        log("mesh " + tag + ": fine end not at the junction -> reverse=" + !cur);
      }
    }
    if (!ok) {
      if (!retry) throw new RuntimeException("mesh grading assertion failed after flipping 'reverse'");
      m.component(COMP).mesh(MESH).run();
      assertMeshGrading(m, false);
    }
  }

