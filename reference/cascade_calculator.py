"""Many-modules calculator (spec §12): why stacking PIN Peltier stages does not help.

    python reference/cascade_calculator.py [--dT-stage 0.005] [--cop 0.2] ...

Writes results/cascade.md.
"""
from __future__ import annotations

import argparse
import math
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "results" / "cascade.md"
DEFAULT_QFLUX = 500.0  # W/m^2, used when no reference result is available


@dataclass
class CascadeInputs:
    dT_stage: float = 5e-3      # K, per-stage lift
    cop: float = 0.2            # per-stage COP
    dT_target: float = 10.0     # K
    Q_load: float = 100.0       # W
    R_c: float = 1e-5           # m^2 K / W, per interface
    q_flux: float = DEFAULT_QFLUX  # W/m^2, per-stage cooling heat flux
    A_module: float = 1e-6      # m^2, module cross-section (Ac)


def reference_q_flux(VF: float = 0.7) -> float | None:
    """Room-side cooling flux of reference V1 at VF (Config A, dT_sink = 0)."""
    path = ROOT / "results" / "reference" / "V1" / "global_vs_VF.csv"
    if not path.exists():
        return None
    import pandas as pd
    from common.params import evaluate_params
    d = pd.read_csv(path, comment="#")
    row = d.iloc[(d.VF - VF).abs().argmin()]
    return float(row.Q_room) / evaluate_params()["Ac"]


def compute(inp: CascadeInputs) -> dict:
    N = math.ceil(inp.dT_target / inp.dT_stage - 1e-12)
    log10_mult = N * math.log10(1.0 + 1.0 / inp.cop)
    # electrical power of the whole cascade: P = Q_load * (prod(1+1/COP) - 1)
    log10_P = math.log10(inp.Q_load) + log10_mult  # (the -1 is negligible)
    dT_interface = inp.R_c * inp.q_flux
    Q1 = inp.q_flux * inp.A_module
    N_mod_parallel = math.ceil(inp.Q_load / Q1) if Q1 > 0 else math.inf
    # Net lift per stage once the interface drop is subtracted. The heat flux at
    # an interface grows stage by stage, so this is the best case (first stage).
    net_stage = inp.dT_stage - dT_interface
    return dict(N_stages=N, log10_power_multiplier=log10_mult, log10_P_el_W=log10_P,
                dT_interface=dT_interface, interface_ratio=dT_interface / inp.dT_stage,
                net_lift_per_stage=net_stage, Q1_module=Q1, N_mod_parallel=N_mod_parallel,
                parallel_area=N_mod_parallel * inp.A_module, parallel_dT=inp.dT_stage,
                parallel_P_el=inp.Q_load / inp.cop)


def verdict(inp: CascadeInputs, r: dict) -> str:
    s = [f"Reaching {inp.dT_target:g} K with {inp.dT_stage*1e3:g} mK per stage needs "
         f"N = {r['N_stages']} thermally series stages. With COP = {inp.cop:g} per stage, the "
         f"electrical power multiplier is prod(1+1/COP) = 10^{r['log10_power_multiplier']:.0f}, "
         f"so cooling {inp.Q_load:g} W would need about 10^{r['log10_P_el_W']:.0f} W. That is not "
         "physically realisable."]
    if r["interface_ratio"] >= 1:
        s.append(f"Each interface also drops R_c*q'' = {r['dT_interface']*1e3:.2f} mK, which is "
                 f"{r['interface_ratio']:.2f}x the per-stage lift, so a stage gives no net lift.")
    else:
        s.append(f"Each interface drops R_c*q'' = {r['dT_interface']*1e3:.2f} mK "
                 f"({r['interface_ratio']*100:.0f}% of the per-stage lift), and that fraction grows "
                 "up the cascade as the heat flux accumulates.")
    s.append(f"Thermally parallel modules only multiply watts: {r['N_mod_parallel']:,} modules "
             f"({r['parallel_area']:.3g} m^2) carry {inp.Q_load:g} W, but the temperature lift "
             f"stays {inp.dT_stage*1e3:g} mK.")
    return " ".join(s)


def write_md(inp: CascadeInputs, r: dict, path: Path = OUT, source: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Many-modules (cascade) calculator", "",
             "Generated by `reference/cascade_calculator.py` (spec §12).", "",
             "## Inputs", "", "| Quantity | Value |", "|---|---|"]
    units = dict(dT_stage="K", cop="-", dT_target="K", Q_load="W", R_c="m^2 K/W",
                 q_flux="W/m^2", A_module="m^2")
    for k, v in asdict(inp).items():
        lines.append(f"| `{k}` | {v:g} {units[k]} |")
    if source:
        lines += ["", f"Per-stage heat flux source: {source}."]
    lines += ["", "## Results", "", "| Quantity | Expression | Value |", "|---|---|---|",
              f"| Stages needed | N = ceil(dT_target/dT_stage) | {r['N_stages']} |",
              f"| Power multiplier | log10 prod(1+1/COP) | {r['log10_power_multiplier']:.1f} |",
              f"| Electrical power for Q_load | log10(P_el / W) | {r['log10_P_el_W']:.1f} |",
              f"| Interface dT | R_c q'' | {r['dT_interface']*1e3:.3f} mK ({r['interface_ratio']:.2f} x dT_stage) |",
              f"| Net lift per stage (best case) | dT_stage - R_c q'' | {r['net_lift_per_stage']*1e3:.3f} mK |",
              f"| Parallel: modules for Q_load | ceil(Q_load/Q_1), Q_1 = q'' A | {r['N_mod_parallel']:,} (Q_1 = {r['Q1_module']*1e3:.3g} mW) |",
              f"| Parallel: total area | N_mod A | {r['parallel_area']:.3g} m^2 |",
              f"| Parallel: dT_max | unchanged | {r['parallel_dT']*1e3:g} mK |",
              "", "## Verdict", "", verdict(inp, r), ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    d = CascadeInputs()
    ap.add_argument("--dT-stage", type=float, default=d.dT_stage)
    ap.add_argument("--cop", type=float, default=d.cop)
    ap.add_argument("--dT-target", type=float, default=d.dT_target)
    ap.add_argument("--Q-load", type=float, default=d.Q_load)
    ap.add_argument("--R-c", type=float, default=d.R_c)
    ap.add_argument("--q-flux", type=float, default=None,
                    help="per-stage heat flux W/m^2 (default: reference V1 at 0.7 V, else 500)")
    a = ap.parse_args(argv)
    if a.q_flux is not None:
        q, src = a.q_flux, "command line"
    else:
        q = reference_q_flux()
        src = "reference model V1, VF = 0.7 V, Config A, dT_sink = 0 (Q_room/Ac)"
        if q is None or q <= 0:
            q, src = DEFAULT_QFLUX, "default (reference results not found)"
    inp = CascadeInputs(a.dT_stage, a.cop, a.dT_target, a.Q_load, a.R_c, q)
    r = compute(inp)
    write_md(inp, r, source=src)
    print(verdict(inp, r))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
